/** Validation failures that mean "not implemented here" rather than "malformed". */
export const UNSUPPORTED_CODES = new Set([
  EvidenceErrorCode.UNSUPPORTED_FORMAT,
  EvidenceErrorCode.UNSUPPORTED_VERSION,
  EvidenceErrorCode.UNSUPPORTED_CANONICALIZATION,
  EvidenceErrorCode.UNSUPPORTED_DIGEST_ALGORITHM,
  EvidenceErrorCode.UNSUPPORTED_SIGNATURE_ALGORITHM,
]);

/** The first validation failure of an evidence document (spec §6). */
export class EvidenceError extends Error {
  /**
   * @param {string} code one of EvidenceErrorCode, or an RNCJ_* code
   * @param {string} message
   * @param {string} subject the dotted field path concerned
   */
  constructor(code, message, subject) {
    super(message);
    this.name = 'EvidenceError';
    this.code = code;
    this.subject = subject;
  }
}
